#!/usr/bin/env node
// Assigns a project rule ID (sast-<language>-<NNNN>) to every rule in an opengrep-rules
// checkout and writes the catalog read by src/core/rule-ids.ts.
//
//   node tools/generate-rule-ids.mjs --rules-dir <opengrep-rules checkout> --source <commit>
//   node tools/generate-rule-ids.mjs --rules-dir <dir> --check   # exit 1 if rules lack an ID
//
// IDs are stable: rules already in the catalog keep their ID, new rules get the next free
// number of their language, and numbers of removed rules are never reused. The language is
// the rule's top-level directory in opengrep-rules (python/, javascript/, generic/, ...).
// Numbers already used by the bundled rules (src/config/opengrep/baseline.yml) are reserved.
import { existsSync, readdirSync, readFileSync, writeFileSync } from 'fs';
import path from 'path';
import { parseArgs } from 'util';
import YAML from 'yaml';

const ROOT = path.join(path.dirname(new URL(import.meta.url).pathname), '..');
const RULE_ID = /^sast-([a-z0-9-]+)-(\d{4,})$/;
const SKIPPED_DIRS = new Set(['.git', '.github', 'scripts', 'stats']);

const { values } = parseArgs({
  options: {
    'rules-dir': { type: 'string' },
    out: { type: 'string', default: path.join(ROOT, 'src/config/opengrep/rule-ids.json') },
    baseline: { type: 'string', default: path.join(ROOT, 'src/config/opengrep/baseline.yml') },
    source: { type: 'string' },
    check: { type: 'boolean', default: false }
  }
});
if (!values['rules-dir']) {
  console.error('usage: generate-rule-ids.mjs --rules-dir <opengrep-rules checkout> [--source <commit>] [--out file] [--check]');
  process.exit(2);
}
const rulesDir = path.resolve(values['rules-dir']);

function* ruleFiles(dir) {
  for (const entry of readdirSync(dir, { withFileTypes: true })) {
    const full = path.join(dir, entry.name);
    if (entry.isDirectory()) yield* ruleFiles(full);
    // *.test.yaml and *.fixed.* are test fixtures, which Opengrep also skips when loading rules.
    else if (entry.isFile() && /\.ya?ml$/.test(entry.name) && !/\.(test|fixed)\./.test(entry.name)) yield full;
  }
}

function ruleIds(file) {
  let doc;
  try {
    doc = YAML.parse(readFileSync(file, 'utf8'));
  } catch {
    return [];
  }
  return Array.isArray(doc?.rules) ? doc.rules.map((rule) => rule?.id).filter((id) => typeof id === 'string') : [];
}

// Every rule key in the checkout, grouped by language.
const found = new Map(); // key -> language
for (const top of readdirSync(rulesDir, { withFileTypes: true })) {
  if (!top.isDirectory() || SKIPPED_DIRS.has(top.name)) continue;
  const language = top.name.toLowerCase().replace(/_/g, '-');
  for (const file of ruleFiles(path.join(rulesDir, top.name))) {
    const dir = path.relative(rulesDir, path.dirname(file)).split(path.sep).join('.');
    for (const id of ruleIds(file)) found.set(`${dir}.${id}`, language);
  }
}

const existing = existsSync(values.out) ? JSON.parse(readFileSync(values.out, 'utf8')) : { ids: {} };
const ids = { ...existing.ids };
const assigned = new Set(Object.values(ids));

// Highest number used per language: catalog plus the bundled rules.
const highest = new Map();
const reserve = (projectId) => {
  const match = RULE_ID.exec(projectId);
  if (match) highest.set(match[1], Math.max(highest.get(match[1]) ?? 0, Number(match[2])));
};
Object.keys(ids).forEach(reserve);
if (existsSync(values.baseline)) ruleIds(values.baseline).forEach(reserve);

const added = [];
for (const key of Array.from(found.keys()).filter((k) => !assigned.has(k)).sort()) {
  const language = found.get(key);
  const next = (highest.get(language) ?? 0) + 1;
  highest.set(language, next);
  const projectId = `sast-${language}-${String(next).padStart(4, '0')}`;
  ids[projectId] = key;
  added.push(projectId);
}

if (values.check) {
  if (added.length) {
    console.error(`${added.length} rule(s) have no project ID; run tools/generate-rule-ids.mjs to assign them.`);
    process.exit(1);
  }
  console.error('All rules have a project ID.');
  process.exit(0);
}

const byLanguageThenNumber = (a, b) => {
  const [, la, na] = RULE_ID.exec(a);
  const [, lb, nb] = RULE_ID.exec(b);
  return la.localeCompare(lb) || Number(na) - Number(nb);
};
const sorted = Object.fromEntries(Object.keys(ids).sort(byLanguageThenNumber).map((id) => [id, ids[id]]));
const catalog = {
  note: 'Generated by tools/generate-rule-ids.mjs. Project ID -> opengrep-rules rule (directory.id). Do not renumber.',
  source: values.source ?? existing.source,
  ids: sorted
};
writeFileSync(values.out, `${JSON.stringify(catalog, null, 2)}\n`);

const perLanguage = {};
for (const id of Object.keys(sorted)) {
  const language = RULE_ID.exec(id)[1];
  perLanguage[language] = (perLanguage[language] ?? 0) + 1;
}
console.error(`${Object.keys(sorted).length} rules (${added.length} new) written to ${path.relative(process.cwd(), values.out)}`);
console.error(Object.entries(perLanguage).map(([language, count]) => `  ${language}: ${count}`).join('\n'));
